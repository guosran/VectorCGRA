#!/usr/bin/env python3
"""
Convert 217-bit IntraCgraPacket hex values to 229-bit format.

Layout change (LSB→MSB order, matching unpack_pkt):
  Old: read_reg_towards = 4×1bit = 4 bits at offset 20
       routing_xbar_outport = 8×3bit = 24 bits at offset 68
  New: read_reg_towards = 4×2bit = 8 bits at offset 20
       routing_xbar_outport = 8×4bit = 32 bits at offset 72
"""

def extract_field(v, offset, width):
    return (v >> offset) & ((1 << width) - 1)

def convert_217_to_229(old_val):
    # --- Extract all fields from old 217-bit value ---
    i = 0
    ctrl_addr        = extract_field(old_val, i, 4);  i += 4
    read_reg_idx     = extract_field(old_val, i, 16); i += 16
    # OLD: 4×1bit = 4 bits
    rrt_raw          = extract_field(old_val, i, 4);  i += 4
    write_reg_idx    = extract_field(old_val, i, 16); i += 16
    write_reg_from   = extract_field(old_val, i, 8);  i += 8
    is_last_ctrl     = extract_field(old_val, i, 1);  i += 1
    vfp              = extract_field(old_val, i, 3);  i += 3
    fu_xbar_outport  = extract_field(old_val, i, 16); i += 16
    # OLD: 8×3bit = 24 bits
    rxo_raw          = extract_field(old_val, i, 24); i += 24
    fu_in            = extract_field(old_val, i, 12); i += 12
    operation        = extract_field(old_val, i, 7);  i += 7
    data_addr        = extract_field(old_val, i, 7);  i += 7
    data_delay       = extract_field(old_val, i, 1);  i += 1
    data_bypass      = extract_field(old_val, i, 1);  i += 1
    data_predicate   = extract_field(old_val, i, 1);  i += 1
    data_payload     = extract_field(old_val, i, 64); i += 64
    cmd              = extract_field(old_val, i, 5);  i += 5
    vc_id            = extract_field(old_val, i, 1);  i += 1
    opaque           = extract_field(old_val, i, 8);  i += 8
    dst_cgra_y       = extract_field(old_val, i, 1);  i += 1
    dst_cgra_x       = extract_field(old_val, i, 1);  i += 1
    src_cgra_y       = extract_field(old_val, i, 1);  i += 1
    src_cgra_x       = extract_field(old_val, i, 1);  i += 1
    dst_cgra_id      = extract_field(old_val, i, 2);  i += 2
    src_cgra_id      = extract_field(old_val, i, 2);  i += 2
    dst              = extract_field(old_val, i, 5);  i += 5
    src              = extract_field(old_val, i, 5);  i += 5
    assert i == 217, f"Old extraction mismatch: {i}"

    # --- Zero-extend read_reg_towards: 4×1bit → 4×2bit ---
    # Each entry was 1 bit, now 2 bits (values 0/1 stay 0/1)
    rrt_new = 0
    for entry in range(4):
        bit = (rrt_raw >> entry) & 1
        rrt_new |= (bit << (entry * 2))

    # --- Zero-extend routing_xbar_outport: 8×3bit → 8×4bit ---
    rxo_new = 0
    for entry in range(8):
        val3 = (rxo_raw >> (entry * 3)) & 0x7
        rxo_new |= (val3 << (entry * 4))

    # --- Pack into new 229-bit value ---
    new_val = 0
    j = 0
    def pack(val, width):
        nonlocal new_val, j
        new_val |= ((val & ((1 << width) - 1)) << j)
        j += width

    pack(ctrl_addr,       4)
    pack(read_reg_idx,    16)
    pack(rrt_new,         8)   # NEW: 4×2bit
    pack(write_reg_idx,   16)
    pack(write_reg_from,  8)
    pack(is_last_ctrl,    1)
    pack(vfp,             3)
    pack(fu_xbar_outport, 16)
    pack(rxo_new,         32)  # NEW: 8×4bit
    pack(fu_in,           12)
    pack(operation,       7)
    pack(data_addr,       7)
    pack(data_delay,      1)
    pack(data_bypass,     1)
    pack(data_predicate,  1)
    pack(data_payload,    64)
    pack(cmd,             5)
    pack(vc_id,           1)
    pack(opaque,          8)
    pack(dst_cgra_y,      1)
    pack(dst_cgra_x,      1)
    pack(src_cgra_y,      1)
    pack(src_cgra_x,      1)
    pack(dst_cgra_id,     2)
    pack(src_cgra_id,     2)
    pack(dst,             5)
    pack(src,             5)
    assert j == 229, f"New packing mismatch: {j}"

    return new_val

